-- 005_questions_reverse.sql
-- 把 12 道符合度题改成「反向题」：作者答案为 'E'（完全不符合）。
--
-- 为什么：原来 39 道符合度题的 author_answer 全是 'A'（完全符合），
--         于是「一路选完全符合」＝ 满分，既不认真也能拿最高档，称号失去区分度。
--         把一部分题翻成反向（作者其实更偏好题面里的另一个选项）之后，
--         只会点「完全符合」的人会在这 12 道上得 0 分，掉出最高档；
--         而认真读题、按真实想法作答的人不受影响（题目本身没有对错）。
--
-- 选哪几道：12 道，铺在 39 道五级题里（占比 31%，接近心理测量学里反向题的常规比例），
--           并且照顾到各个能出五级题的维度，避免某个维度的分数被系统性带偏：
--             吃喝日常 sort_order 11、25、34
--             数码科技 sort_order 5、13、28
--             生活节奏 sort_order 17
--             审美性情 sort_order 19
--             处世之道 sort_order 40、44、47、51
--           —— 不要出现「隔一道翻一道」「后半段全翻」这类一眼能摸出来的规律。
--           改这几道之前，用仓库根的 _subcheck.mjs 量过效果：
--             只点「完全符合」的策略由 76% 掉到 55%（14 道 → 52%、16 道 → 48.6%），
--             而诚实作答者仍是 100%、随机乱点仍是 38% 左右（期望 37.6 不变）。
--
-- 幂等：只更新「当前仍是 'A'」且确实是五级符合度题的行；重复执行不会二次改动，
--       也不会碰其他题。选项、题干、type、sort_order 一律不动。
-- 应用：wrangler d1 execute matching-quiz-db --remote --file=./migrations/005_questions_reverse.sql --yes

UPDATE questions
SET author_answer = 'E'
WHERE author_answer = 'A'
  AND type = 'single'
  AND options LIKE '%完全不符合%'
  AND sort_order IN (5, 11, 13, 17, 19, 25, 28, 34, 40, 44, 47, 51);
